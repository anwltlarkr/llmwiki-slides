from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import re
import tempfile
from pathlib import Path
from typing import Any
from urllib.parse import quote


def _slug(value: str) -> str:
    stem = Path(value).stem.casefold()
    slug = re.sub(r"[^\w가-힣.-]+", "-", stem, flags=re.UNICODE).strip("-.")
    return (slug[:100] or "presentation").strip("-.")


def _yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _markdown_text(value: Any) -> str:
    text = str(value or "")
    return text.replace("[[", "\\[\\[").replace("]]", "\\]\\]")


def _date(value: str, fallback: str) -> str:
    match = re.search(r"\d{4}-\d{2}-\d{2}", value or "")
    return match.group(0) if match else fallback


def _classification_labels(classification: dict[str, list[dict[str, Any]]], axis: str) -> list[str]:
    return [str(item["name"]) for item in classification.get(axis, [])]


def source_page_path(output_dir: Path, result: dict[str, Any]) -> Path:
    candidate = result["candidate"]
    path_hash = hashlib.sha1(candidate["path"].encode("utf-8", errors="surrogateescape")).hexdigest()[:10]
    return output_dir / f"{_slug(candidate['filename'])}-{path_hash}.md"


def render_markdown(result: dict[str, Any]) -> str:
    candidate = result["candidate"]
    classification = result.get("classification", {})
    today = dt.date.today().isoformat()
    created = _date(result.get("internal_created", "") or candidate.get("created_time", ""), today)
    projects = ["presentation-archive"] + _classification_labels(classification, "project")
    projects = list(dict.fromkeys(projects))
    status = "needs-review" if result.get("needs_visual_review") else "summarized"
    if result.get("extraction_status") == "needs-conversion":
        status = "needs-review"

    tags = [
        f"file/{candidate['extension'].lstrip('.')}",
        "project/presentation-archive",
        "output/presentation",
        f"status/{status}",
    ]
    tag_prefix = {
        "project": "project",
        "topic": "topic",
        "presentation_type": "presentation",
        "event": "event",
        "audience": "audience",
        "output_relation": "output",
    }
    for axis, prefix in tag_prefix.items():
        tags.extend(f"{prefix}/{name}" for name in _classification_labels(classification, axis))
    tags = list(dict.fromkeys(tags))

    lines = [
        "---",
        "type: source",
        f"file_type: {candidate['extension'].lstrip('.')}",
        f"source_path: {_yaml_string(candidate['path'])}",
        "project:",
    ]
    lines.extend(f"  - {project}" for project in projects)
    lines.append("tags:")
    lines.extend(f"  - {tag}" for tag in tags)
    lines.extend([
        f"status: {status}",
        "tier: 2",
        f"created: {created}",
        f"updated: {today}",
        f"content_hash: {_yaml_string(result.get('content_hash', ''))}",
        "generator: llmwiki-slides/0.1.0",
        "---",
        "",
        f"# {_markdown_text(candidate['filename'])}",
        "",
        "<!-- Generated by llmwiki-slides. Edit vocabulary or source metadata, then regenerate. -->",
        "",
        "## Summary",
        "",
        _markdown_text(result.get("summary", "No summary available.")),
        "",
        "## Source",
        "",
        f"- Original path: `{candidate['path']}`",
        f"- Open original: [file link](file://{quote(candidate['path'])})",
        f"- File type: `{candidate['extension']}`",
        f"- Size: `{candidate.get('size_bytes', 0)}` bytes",
        f"- Filesystem created: `{candidate.get('created_time', '')}`",
        f"- Filesystem modified: `{candidate.get('modified_time', '')}`",
        f"- Content hash: `{result.get('content_hash', '')}`",
        f"- Extraction status: `{result.get('extraction_status', '')}`",
        f"- Converted derivative: `{result.get('derivative_path') or 'not used'}`",
        f"- Conversion method: `{result.get('conversion_method') or 'not used'}`",
        f"- Title metadata: {_markdown_text(result.get('title') or 'not available')}",
        f"- Creator: {_markdown_text(result.get('creator') or result.get('spotlight_authors') or 'not available')}",
        f"- Last modified by: {_markdown_text(result.get('last_modified_by') or 'not available')}",
        f"- Recently opened: {result.get('spotlight_last_used') or 'not available'}",
        "",
        "## Classification",
        "",
        "| Axis | Labels |",
        "|---|---|",
    ])
    if classification:
        for axis, matches in classification.items():
            labels = "; ".join(f"{item['name']} ({item['score']})" for item in matches)
            lines.append(f"| {axis} | {labels} |")
    else:
        lines.append("| unclassified | needs review |")

    keywords = result.get("keywords", [])
    lines.extend([
        "",
        "## Frequent Keywords",
        "",
        ", ".join(
            f"`{item['term']}` ({item['count']} occurrences / {item['slide_count']} slides)"
            for item in keywords
        ) or "No slide text was available for keyword extraction.",
        "",
        "## Visual Review",
        "",
        f"- Needed: `{'yes' if result.get('needs_visual_review') else 'no'}`",
        f"- Reasons: {'; '.join(result.get('visual_review_reasons', [])) or 'none'}",
        f"- Theme colors: {', '.join(f'`{color}`' for color in result.get('theme_colors', [])) or 'not extracted'}",
        "",
        "## Slide Outline",
        "",
    ])
    slides = result.get("slides", [])
    if not slides:
        lines.append("Slide-level content is unavailable until this presentation is converted to PPTX or ODP.")
    else:
        for slide in slides:
            title = _markdown_text(slide.get("title") or "Untitled slide")
            lines.append(
                f"- Slide {slide['number']}: **{title}** "
                f"({slide.get('word_count', 0)} words; {slide.get('image_count', 0)} images; "
                f"{slide.get('table_count', 0)} tables; {slide.get('chart_count', 0)} charts)"
            )
        lines.extend(["", "## Indexed Slide Text", ""])
        for slide in slides:
            title = _markdown_text(slide.get("title") or "Untitled slide")
            lines.extend([
                f"### Slide {slide['number']}: {title}",
                "",
                _markdown_text(slide.get("body")) or "_No additional text extracted._",
                "",
            ])
            if slide.get("notes"):
                lines.extend(["#### Speaker Notes", "", _markdown_text(slide["notes"]), ""])
    return "\n".join(lines).rstrip() + "\n"


def export_markdown(output_dir: Path, result: dict[str, Any]) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    destination = source_page_path(output_dir, result)
    text = render_markdown(result)
    descriptor, temporary = tempfile.mkstemp(prefix=destination.name + ".", suffix=".tmp", dir=output_dir)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, destination)
    except Exception:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise
    return destination
